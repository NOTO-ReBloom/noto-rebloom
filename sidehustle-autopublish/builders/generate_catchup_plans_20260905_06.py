def longform(intro1, intro2, sections, closing):
    return {"intro": [intro1, intro2], "sections": sections, "closing": closing}


def paid(queue_id, title, tags, teaser, intro1, intro2, sections, closing, price=980):
    return {
        "id": queue_id, "title": title, "price": price, "tags": tags, "free": teaser,
        "longform": longform(intro1, intro2, sections, closing),
    }


